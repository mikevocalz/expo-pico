#!/usr/bin/env node
/**
 * Builds the Lucide icon table consumed by the Eskiu icon mesher.
 *
 * Downloads `lucide-static` from npm (latest unless --version is given), reads
 * its 24x24 SVGs, and writes a map of icon name -> SVG element markup (the
 * children of each <svg>). The Eskiu runtime turns that markup into a stroke
 * mesh, see packages/internal/pico-eskiu-runtime/src/icon/.
 *
 *   node scripts/build-lucide-icons.mjs
 *       Regenerates the curated set committed for the example and tests:
 *       packages/expo-pico-core/src/icons/lucideIcons.generated.ts
 *
 *   node scripts/build-lucide-icons.mjs --all [--out file.json]
 *       Writes every icon as JSON for a build step. The full set (~2,000 icons)
 *       is not committed; the default output lives under node_modules/.cache.
 *
 *   --version <semver>   lucide-static version (default: latest)
 *   --icons a,b,c        icon names for the TypeScript output (default: CURATED)
 *   --format ts|json     output format (default: ts, or json with --all)
 *
 * Lucide is ISC-licensed; the generated file carries its license notice.
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PRETTIER = join(ROOT, 'node_modules/prettier/bin/prettier.cjs');

/** Icons committed to the repo: the ones the example and the mesher tests use. */
export const CURATED = [
  'check',
  'chevron-right',
  'circle',
  'heart',
  'house',
  'map-pin',
  'search',
  'settings',
  'star',
  'x',
];

function parseArgs(argv) {
  const args = { version: 'latest', icons: null, all: false, out: null, format: null };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    const next = () => {
      const v = argv[++i];
      if (v === undefined) throw new Error(`${a} needs a value`);
      return v;
    };
    if (a === '--version') args.version = next();
    else if (a === '--icons')
      args.icons = next()
        .split(',')
        .map((s) => s.trim())
        .filter(Boolean);
    else if (a === '--all') args.all = true;
    else if (a === '--out') args.out = next();
    else if (a === '--format') args.format = next();
    else throw new Error(`unknown argument: ${a}`);
  }
  args.format ??= args.all ? 'json' : 'ts';
  if (args.format !== 'ts' && args.format !== 'json') {
    throw new Error(`--format must be ts or json, got ${args.format}`);
  }
  return args;
}

/** Fetches and unpacks lucide-static into a temp dir. Returns its package root. */
function fetchLucide(version, workDir) {
  const out = execFileSync(
    'npm',
    ['pack', `lucide-static@${version}`, '--json', '--silent', '--pack-destination', workDir],
    { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] }
  );
  const [{ filename }] = JSON.parse(out);
  execFileSync('tar', ['-xzf', join(workDir, filename), '-C', workDir]);
  return join(workDir, 'package');
}

/** Returns the markup between <svg ...> and </svg>, whitespace-collapsed. */
export function svgChildren(svg) {
  const open = svg.indexOf('<svg');
  const openEnd = open < 0 ? -1 : svg.indexOf('>', open);
  const close = svg.lastIndexOf('</svg>');
  if (openEnd < 0 || close < openEnd) throw new Error('not an <svg> document');
  return svg
    .slice(openEnd + 1, close)
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+/g, ' ')
    .replace(/\s*\/>/g, '/>')
    .replace(/>\s+</g, '><')
    .trim();
}

function readIcons(pkgDir, names) {
  const iconDir = join(pkgDir, 'icons');
  const available = readdirSync(iconDir)
    .filter((f) => f.endsWith('.svg'))
    .map((f) => f.slice(0, -4))
    .sort();
  const wanted = names ?? available;
  const missing = wanted.filter((n) => !available.includes(n));
  if (missing.length) throw new Error(`lucide-static has no icon named: ${missing.join(', ')}`);
  const table = {};
  for (const name of wanted) {
    table[name] = svgChildren(readFileSync(join(iconDir, `${name}.svg`), 'utf8'));
  }
  return table;
}

function renderTs(version, license, table) {
  const notice = license
    .trim()
    .split('\n')
    .map((l) => (l ? ` * ${l}` : ' *'))
    .join('\n');
  const entries = Object.entries(table)
    .map(([name, markup]) => `  '${name}': ${JSON.stringify(markup)},`)
    .join('\n');
  return `// Generated by scripts/build-lucide-icons.mjs from lucide-static@${version}. Do not edit.
// Regenerate with: node scripts/build-lucide-icons.mjs
/**
 * Icon geometry from Lucide (https://lucide.dev), used under the ISC license:
 *
${notice}
 */

export const LUCIDE_VERSION = '${version}';

/** Lucide icon name -> SVG element markup on Lucide's 24x24 grid. */
export const LUCIDE_ICONS = {
${entries}
} as const;

export type LucideIconName = keyof typeof LUCIDE_ICONS;
`;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const work = mkdtempSync(join(tmpdir(), 'lucide-static-'));
  try {
    const pkgDir = fetchLucide(args.version, work);
    const version = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version;
    const license = readFileSync(join(pkgDir, 'LICENSE'), 'utf8');
    const names = args.all ? null : (args.icons ?? CURATED);
    const table = readIcons(pkgDir, names);
    const defaultOut =
      args.format === 'json'
        ? join(ROOT, 'node_modules/.cache/expo-pico/lucide-icons.json')
        : join(ROOT, 'packages/expo-pico-core/src/icons/lucideIcons.generated.ts');
    const out = resolve(args.out ?? defaultOut);
    mkdirSync(dirname(out), { recursive: true });
    const body =
      args.format === 'json'
        ? JSON.stringify({ version, license, icons: table }) + '\n'
        : renderTs(version, license, table);
    writeFileSync(out, body);
    if (args.format === 'ts') {
      // Match the repo's formatting so a regenerated file passes prettier:check.
      execFileSync(process.execPath, [PRETTIER, '--write', '--log-level', 'warn', out], {
        stdio: 'inherit',
      });
    }
    console.log(`lucide-static@${version}: ${Object.keys(table).length} icons -> ${out}`);
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
